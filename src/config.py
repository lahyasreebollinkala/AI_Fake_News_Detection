"""Central configuration for the Veritas news-authenticity pipeline.

Every path used by the training scripts and the Streamlit app is declared here so
that the pipeline has a single source of truth. Import this module instead of
hard-coding paths.
"""

from __future__ import annotations

from pathlib import Path

# --------------------------------------------------------------------------
# Project root
# --------------------------------------------------------------------------

ROOT_DIR = Path(__file__).resolve().parent.parent

# --------------------------------------------------------------------------
# Directories
# --------------------------------------------------------------------------

DATA_DIR = ROOT_DIR / "data"
MODEL_DIR = ROOT_DIR / "models"
IMAGE_DIR = ROOT_DIR / "images"
RESULT_DIR = ROOT_DIR / "results"
DOC_DIR = ROOT_DIR / "docs"

ALL_DIRS = (DATA_DIR, MODEL_DIR, IMAGE_DIR, RESULT_DIR, DOC_DIR)


def ensure_dirs() -> None:
    """Create every output directory the pipeline writes to."""
    for directory in ALL_DIRS:
        directory.mkdir(parents=True, exist_ok=True)


# --------------------------------------------------------------------------
# Raw / derived datasets
# --------------------------------------------------------------------------

#: Optional full-size sources from the Kaggle "Fake and Real News Dataset".
#: When present they are preferred over the bundled sample corpus.
FAKE_RAW = DATA_DIR / "Fake.csv"
TRUE_RAW = DATA_DIR / "True.csv"

#: Bundled, versioned corpus that ships with the repository.
SAMPLE_DATA = DATA_DIR / "sample_dataset.csv"

#: Merged + engineered dataset (``src.prepare_dataset``).
RAW_DATA = DATA_DIR / "GlobalFakeNews_Research2026_v1.csv"

#: NLP-cleaned training data (``src.preprocessing``).
CLEAN_DATA = DATA_DIR / "cleaned_news.csv"

# --------------------------------------------------------------------------
# Model & feature artifacts
# --------------------------------------------------------------------------

BEST_MODEL = MODEL_DIR / "best_model.pkl"
VECTORIZER = MODEL_DIR / "vectorizer.pkl"
FEATURE_NAMES = MODEL_DIR / "feature_names.pkl"

XTRAIN = MODEL_DIR / "X_train.pkl"
XTEST = MODEL_DIR / "X_test.pkl"
YTRAIN = MODEL_DIR / "y_train.pkl"
YTEST = MODEL_DIR / "y_test.pkl"

# --------------------------------------------------------------------------
# Results & reports
# --------------------------------------------------------------------------

METRICS_FILE = RESULT_DIR / "model_metrics.json"
REPRESENTATION_REPORT = RESULT_DIR / "representation_benchmark.csv"
DATASET_PROFILE = RESULT_DIR / "dataset_profile.json"
PREDICTION_HISTORY = RESULT_DIR / "prediction_history.csv"

#: Rendered documentation (regenerated by ``python -m src.report``).
#: ``.md`` is the canonical source, ``.tex`` is the ``IEEEtran`` build, ``.html``
#: is the two-column printable layout, and ``.pdf`` is produced from whichever
#: of LaTeX or a headless browser is available.
REPORT_MARKDOWN = DOC_DIR / "ieee_report.md"
REPORT_LATEX = DOC_DIR / "ieee_report.tex"
REPORT_HTML = DOC_DIR / "ieee_report.html"
REPORT_PDF = DOC_DIR / "ieee_report.pdf"

# --------------------------------------------------------------------------
# Training hyper-parameters
# --------------------------------------------------------------------------

RANDOM_STATE = 42
TEST_SIZE = 0.20

#: Fraction of the *training* split held back to choose the model. Selecting on
#: the test split would turn the reported scores into an optimistic estimate, so
#: the choice is made here instead and the test split is scored once.
VALIDATION_SIZE = 0.20

MAX_FEATURES = 5000
NGRAM_RANGE = (1, 2)
MIN_DF = 2

#: Rank of the latent-semantic embedding fitted by ``src.feature_extraction``.
#: ``src.embeddings`` holds a from-scratch NumPy implementation of the same
#: factorisation (plus a skip-gram word2vec) kept for reference and testing.
EMBEDDING_COMPONENTS = 200
EMBEDDING_SEED = RANDOM_STATE

#: Canonical names of the three required feature-extraction representations.
REPRESENTATIONS = ("Bag-of-Words", "TF-IDF", "Embeddings (LSA)")

#: Human-readable label map shared by the scripts and the app.
LABEL_NAMES = {0: "REAL", 1: "FAKE"}

#: Columns produced by ``src.prepare_dataset`` and consumed by the app.
ENGINEERED_FEATURES = [
    "sentiment_score",
    "clickbait_score",
    "emotional_word_ratio",
    "readability_score",
    "source_trust_score",
]
